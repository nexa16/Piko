import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:piko/shared/generated_catalogs.dart';

Iterable<File> productionSources() => Directory('lib')
    .listSync(recursive: true)
    .whereType<File>()
    .where(
      (file) =>
          file.path.endsWith('.dart') &&
          !file.path.endsWith('.g.dart') &&
          !file.path.endsWith('generated_catalogs.dart'),
    );

void main() {
  test('Android application label consumes generated canonical app.name', () {
    final manifest = File(
      'android/app/src/main/AndroidManifest.xml',
    ).readAsStringSync();
    expect(manifest, contains('android:label="@string/app_name"'));
    expect(manifest, isNot(contains('android:label="piko"')));

    final entries = copyCatalog['entries']! as Map<String, Object?>;
    final appName = entries['app.name']! as Map<String, Object?>;
    String escaped(String value) => value
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&apos;');
    for (final (locale, qualifier) in [('en', 'values'), ('de', 'values-de')]) {
      final resource = File(
        'android/app/src/main/res/$qualifier/generated_copy.xml',
      ).readAsStringSync();
      expect(resource, contains('Generated by app/tool/generate_shared.mjs'));
      expect(
        resource,
        contains(
          '<string name="app_name">'
          '${escaped(appName[locale]! as String)}</string>',
        ),
      );
    }
  });

  test('every production copy-key reference has English and German text', () {
    final entries = copyCatalog['entries']! as Map<String, Object?>;
    final referenced = <String>{};
    final copyKey = RegExp(
      r'''['"]((?:action|app|collection|common|dialog|direction|entry|home|import|language|learn|metric|nav|prototype|settings|stats|summary|view|vocab)\.[A-Za-z][A-Za-z0-9.]*)['"]''',
    );

    for (final file in productionSources()) {
      for (final match in copyKey.allMatches(file.readAsStringSync())) {
        referenced.add(match.group(1)!);
      }
    }

    expect(referenced, isNotEmpty);
    for (final key in referenced) {
      expect(entries, contains(key), reason: 'Missing canonical copy for $key');
      final entry = entries[key]! as Map<String, Object?>;
      for (final locale in ['en', 'de']) {
        expect(
          entry[locale],
          isA<String>().having(
            (value) => value.trim(),
            '$locale text',
            isNotEmpty,
          ),
          reason: '$key must support $locale',
        );
      }
    }
  });

  test('visible widget arguments contain no direct natural-language literal', () {
    // Interpolated values are separately reviewed compositions of localized
    // catalog text, numbers, punctuation or stored user content. This catches
    // a direct Text('Loading'), label: 'Retry', tooltip, dialog title, and the
    // equivalent visible/accessibility regressions anywhere in production.
    final directText = RegExp(
      r'''Text\s*\(\s*(?:const\s*)?r?(['"])(?!\$|\1)''',
      dotAll: true,
    );
    final directNamedArgument = RegExp(
      r'''(?:label|semanticLabel|tooltip|message|title|hintText|helperText|errorText)\s*:\s*r?(['"])(?!\$|\1)''',
      dotAll: true,
    );
    final violations = <String>[];

    for (final file in productionSources()) {
      final source = file.readAsStringSync();
      for (final pattern in [directText, directNamedArgument]) {
        for (final match in pattern.allMatches(source)) {
          final line =
              '\n'.allMatches(source.substring(0, match.start)).length + 1;
          violations.add('${file.path}:$line');
        }
      }
    }

    expect(
      violations,
      isEmpty,
      reason:
          'Visible natural-language literals must come from shared/copy.js. '
          'Developer diagnostics and storage identifiers are not visible '
          'widget arguments.',
    );
  });
}
