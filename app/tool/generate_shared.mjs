import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const output = path.join(root, 'app/lib/shared/generated_catalogs.dart');
export const placeholders = text => [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(match => match[1]))].sort();

export function validate(design, copy) {
  if (design.schemaVersion !== 1 || copy.schemaVersion !== 1) throw Error('Unsupported catalog schema');
  if (!['en', 'de'].includes(copy.defaultLocale)) throw Error('Unsupported default locale');
  for (const [key, entry] of Object.entries(copy.entries)) {
    if (typeof entry.en !== 'string' || typeof entry.de !== 'string') throw Error(`Missing translation: ${key}`);
    if (JSON.stringify(placeholders(entry.en)) !== JSON.stringify(placeholders(entry.de))) throw Error(`Placeholder mismatch: ${key}`);
  }
}

function dart(value) {
  if (typeof value === 'string') return JSON.stringify(value).replaceAll('$', '\\$');
  if (typeof value === 'number' && Number.isFinite(value)) return String(value);
  if (typeof value === 'boolean' || value === null) return String(value);
  if (Array.isArray(value)) return `<Object?>[${value.map(dart).join(', ')}]`;
  if (typeof value === 'object') return `<String, Object?>{\n${Object.keys(value).sort().map(key => `${dart(key)}: ${dart(value[key])},`).join('\n')}\n}`;
  throw Error('Catalog contains an unsupported value');
}

export function generate(design, copy) {
  validate(design, copy);
  return '// Generated by app/tool/generate_shared.mjs. Edit shared sources only.\n'
    + '// dart format off\n'
    + `const designCatalog = ${dart(design)};\nconst copyCatalog = ${dart(copy)};\n`;
}

function xml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

export function androidStringResources(copy, locale) {
  if (copy.schemaVersion !== 1 || !['en', 'de'].includes(locale)) {
    throw Error('Unsupported Android copy catalog or locale');
  }
  const appName = copy.entries?.['app.name']?.[locale];
  if (typeof appName !== 'string' || appName.trim() === '') {
    throw Error(`Missing canonical Android app name: ${locale}`);
  }
  return '<?xml version="1.0" encoding="utf-8"?>\n'
    + '<!-- Generated by app/tool/generate_shared.mjs. Edit shared/copy.js only. -->\n'
    + '<resources>\n'
    + `    <string name="app_name">${xml(appName)}</string>\n`
    + '</resources>\n';
}

export function readCatalog(file, globalName) {
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(file, 'utf8'), context, { timeout: 1000 });
  // Validate before JSON normalization, which would silently turn NaN/Infinity
  // into null and drop undefined/function values from objects.
  const seen = new Set();
  function verify(value) {
    if (value === null || typeof value === 'string' || typeof value === 'boolean') return;
    if (typeof value === 'number' && Number.isFinite(value)) return;
    if (typeof value !== 'object' || seen.has(value)) throw Error('Catalog contains an unsupported or circular value');
    seen.add(value);
    for (const nested of Object.values(value)) verify(nested);
    seen.delete(value);
  }
  verify(context[globalName]);
  return JSON.parse(JSON.stringify(context[globalName]));
}

export function update(file, contents, check) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) throw Error('Generated catalogs are stale; run node app/tool/generate_shared.mjs');
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, contents);
  }
}

export function entryHeaderResponsive(design, css) {
  const breakpoint = design.components.entryHeader.compactBreakpoint;
  if (!Number.isFinite(breakpoint) || breakpoint < 280 || breakpoint > 2000) throw Error('Invalid entry header breakpoint');
  const block = '/* Generated entry header responsive adapter; edit shared/design-config.js only. */\n'
    + `@media(max-width:${breakpoint}px){.entry-header h1{font-size:var(--entry-header-compact-title-size)}.entry-header .back{font-size:var(--font-small)}.entry-header .entry-complete{padding:var(--entry-header-action-padding)}}\n`
    + '/* End generated entry header responsive adapter. */';
  const pattern = /\/\* Generated entry header responsive adapter;[^]*?\/\* End generated entry header responsive adapter\. \*\//;
  return pattern.test(css) ? css.replace(pattern, block) : css.trimEnd() + '\n' + block + '\n';
}

